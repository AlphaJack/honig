//! The edge: every file the generator reads or writes goes through here. `clippy.toml` bans `std::fs` everywhere else.

use std::path::Path;

use crate::error::Error;

/// Returns an I/O error on `path`.
fn failed(path: &Path) -> impl Fn(std::io::Error) -> Error + '_ {
    move |source| Error::Io { path: path.to_path_buf(), source }
}

/// Returns the text of the file at `path`.
///
/// # Errors
/// The file cannot be read. The error has its path.
#[expect(clippy::disallowed_methods, reason = "the edge reads files")]
pub(crate) fn read(path: &Path) -> Result<String, Error> {
    std::fs::read_to_string(path).map_err(failed(path))
}

/// Returns whether `path` is a file.
#[expect(clippy::disallowed_methods, reason = "the edge reads files")]
pub(crate) fn is_file(path: &Path) -> bool {
    path.is_file()
}

/// Returns the files directly in `dir`, sorted by path.
///
/// # Errors
/// The folder cannot be read. The error has its path.
#[expect(clippy::disallowed_methods, reason = "the edge reads folders")]
pub(crate) fn files_in(dir: &Path) -> Result<Vec<std::path::PathBuf>, Error> {
    let mut out: Vec<_> = std::fs::read_dir(dir)
        .map_err(failed(dir))?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_file())
        .collect();
    out.sort();
    Ok(out)
}

/// Returns the folders directly in `dir`, sorted.
///
/// # Errors
/// The folder cannot be read. The error has its path.
#[expect(clippy::disallowed_methods, reason = "the edge reads folders")]
pub(crate) fn dirs_in(dir: &Path) -> Result<Vec<std::path::PathBuf>, Error> {
    let mut out: Vec<_> = std::fs::read_dir(dir)
        .map_err(failed(dir))?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    out.sort();
    Ok(out)
}

/// Writes `text` to `path` and creates its folder. A file that already holds `text` is left as it is, so Cargo does
/// not rebuild it.
///
/// # Errors
/// The file or its folder cannot be written. The error has its path.
#[expect(clippy::disallowed_methods, reason = "the edge writes files")]
pub(crate) fn write(path: &Path, text: &str) -> Result<(), Error> {
    if std::fs::read(path).is_ok_and(|old| old == text.as_bytes()) {
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(failed(path))?;
    }
    std::fs::write(path, text).map_err(failed(path))
}

/// Writes `files` named relative to `dir`, the root (`mod.rs`) at `root`. Removes the `.rs` files that an earlier run
/// left in `dir`, and a root that an earlier run wrote as `<dir>.rs`.
///
/// # Errors
/// A file cannot be written or removed. The error has its path.
#[expect(clippy::disallowed_methods, reason = "the edge writes files")]
pub(crate) fn write_module(dir: &Path, root: &Path, files: &[(String, String)]) -> Result<(), Error> {
    for (name, code) in files {
        write(&placed(dir, root, name), code)?;
    }
    let entries = std::fs::read_dir(dir).map_err(failed(dir))?;
    for path in entries.filter_map(|e| Some(e.ok()?.path())) {
        let written = files.iter().any(|(f, _)| placed(dir, root, f) == path);
        if path.extension().is_some_and(|e| e == "rs") && !written {
            std::fs::remove_file(&path).map_err(failed(&path))?;
        }
    }
    let beside = dir.with_extension("rs");
    if beside != root && is_generated(&beside) {
        std::fs::remove_file(&beside).map_err(failed(&beside))?;
    }
    Ok(())
}

/// The name of the root of a module as the emitter returns it, whatever `mod_rs` says.
pub(crate) const ROOT_FILE: &str = "mod.rs";

/// Returns where the generated file `name` goes: the root at `root`, the others in `dir`.
pub(crate) fn placed(dir: &Path, root: &Path, name: &str) -> std::path::PathBuf {
    if name == ROOT_FILE { root.to_path_buf() } else { dir.join(name) }
}

/// Is `path` a file that honig wrote? Its first line is the `@generated` marker.
pub(crate) fn is_generated(path: &Path) -> bool {
    read(path).is_ok_and(|text| text.starts_with("// @generated by honig"))
}

/// Returns `path` with links, `.` and `..` resolved. As given when it does not exist.
#[expect(clippy::disallowed_methods, reason = "the edge asks the file system")]
pub(crate) fn canonical(path: std::path::PathBuf) -> std::path::PathBuf {
    std::fs::canonicalize(&path).unwrap_or(path)
}

/// Returns the workspace of the manifest at `path` as `cargo metadata --no-deps` resolves it.
///
/// # Errors
/// Cargo cannot be run or rejects the manifest.
pub(crate) fn cargo_metadata(path: &Path) -> Result<cargo_metadata::Metadata, Error> {
    cargo_metadata::MetadataCommand::new()
        .manifest_path(path)
        .no_deps()
        .exec()
        .map_err(|e| Error::Metadata { path: path.to_path_buf(), problem: e.to_string() })
}

#[cfg(test)]
mod tests {
    #![expect(clippy::disallowed_methods, reason = "the test reads and dates a file")]

    use std::time::{Duration, SystemTime};

    /// A second `generate` with the same output leaves the file and its time alone: Cargo rebuilds nothing.
    #[test]
    fn writing_the_same_text_keeps_the_file_time() {
        let path = std::env::temp_dir().join(format!("honig-same-text-{}.rs", std::process::id()));
        super::write(&path, "x").unwrap();
        let old = SystemTime::UNIX_EPOCH + Duration::from_secs(1_000_000);
        std::fs::File::options().write(true).open(&path).unwrap().set_modified(old).unwrap();
        super::write(&path, "x").unwrap();
        assert_eq!(std::fs::metadata(&path).unwrap().modified().unwrap(), old);
        super::write(&path, "y").unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "y");
        std::fs::remove_file(&path).unwrap();
    }
}
